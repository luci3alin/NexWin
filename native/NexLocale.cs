using System;
using System.Collections.Generic;
using System.IO;
using System.Text.Json;

namespace NexWin.Native;

public enum AppLanguage
{
    Ro,
    En
}

public static class NexLocale
{
    private static readonly string SettingsDirectory = Path.Combine(
        Environment.GetFolderPath(Environment.SpecialFolder.LocalApplicationData), "NexWin");
    private static readonly string SettingsFilePath = Path.Combine(SettingsDirectory, "settings.json");

    public static AppLanguage CurrentLanguage { get; private set; } = AppLanguage.Ro;

    public static event Action? LanguageChanged;

    static NexLocale()
    {
        LoadSettings();
    }

    public static void LoadSettings()
    {
        try
        {
            if (File.Exists(SettingsFilePath))
            {
                string json = File.ReadAllText(SettingsFilePath);
                using var doc = JsonDocument.Parse(json);
                if (doc.RootElement.TryGetProperty("language", out var langProp))
                {
                    string langStr = langProp.GetString() ?? "ro";
                    CurrentLanguage = langStr.Equals("en", StringComparison.OrdinalIgnoreCase)
                        ? AppLanguage.En
                        : AppLanguage.Ro;
                }
            }
        }
        catch
        {
            CurrentLanguage = AppLanguage.Ro;
        }
    }

    public static void SetLanguage(AppLanguage language)
    {
        if (CurrentLanguage == language) return;
        CurrentLanguage = language;
        SaveSettings();
        LanguageChanged?.Invoke();
    }

    public static void SaveSettings()
    {
        try
        {
            Directory.CreateDirectory(SettingsDirectory);
            var data = new Dictionary<string, object>
            {
                ["language"] = CurrentLanguage == AppLanguage.En ? "en" : "ro",
                ["updatedAt"] = DateTime.UtcNow.ToString("o")
            };
            string json = JsonSerializer.Serialize(data, new JsonSerializerOptions { WriteIndented = true });
            File.WriteAllText(SettingsFilePath, json);
        }
        catch { }
    }

    public static string T(string key, string? defaultText = null)
    {
        if (string.IsNullOrEmpty(key)) return defaultText ?? "";

        var dict = CurrentLanguage == AppLanguage.En ? StringsEn : StringsRo;
        if (dict.TryGetValue(key, out var translation))
        {
            return translation;
        }

        // Fallback to Romanian dictionary if missing in English
        if (CurrentLanguage == AppLanguage.En && StringsRo.TryGetValue(key, out var roFallback))
        {
            return roFallback;
        }

        return defaultText ?? key;
    }

    public static string Format(string key, params object[] args)
    {
        string pattern = T(key);
        try
        {
            return string.Format(pattern, args);
        }
        catch
        {
            return pattern;
        }
    }

